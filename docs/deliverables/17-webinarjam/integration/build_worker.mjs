// Builds dist/worker.js: register.mjs + lib.mjs + funnel-config.json in one file, for pasting into the
// Cloudflare dashboard editor (no wrangler needed). Run again after funnel-config.json changes:
//   node deliverables/17-webinarjam/integration/build_worker.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const cfg = JSON.parse(readFileSync(path.join(here, '../../_shared/funnel-config.json'), 'utf8'));
// Only what the Worker reads ships in the bundle.
const keep = { webinar: { duration_minutes: cfg.webinar.duration_minutes, day_of_week: cfg.webinar.day_of_week, start_time_local: cfg.webinar.start_time_local, timezone: cfg.webinar.timezone, first_date: cfg.webinar.first_date }, domains: cfg.domains,
  integrations: { crm_webhook_url: cfg.integrations.crm_webhook_url, webinarjam_webinar_id: cfg.integrations.webinarjam_webinar_id } };
const lib = readFileSync(path.join(here, 'lib.mjs'), 'utf8').replace(/^export (const|function|async function) /gm, '$1 ');
let reg = readFileSync(path.join(here, 'register.mjs'), 'utf8');
reg = reg.split('// ---------- CLI ----------')[0].replace(/^import .*$/gm, '').replace(/^export (const|function|async function) /gm, '$1 ');
const out = `// GENERATED by build_worker.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit; edit register.mjs and rebuild.\n` +
  `const config = ${JSON.stringify(keep, null, 2)};\n\n${lib}\n${reg}`;
mkdirSync(path.join(here, '../dist'), { recursive: true });
writeFileSync(path.join(here, '../dist/worker.js'), out);
console.log(`dist/worker.js written (${out.length} bytes)`);

#!/usr/bin/env node
// Reads the deck spec (item 16) and funnel-config.json and writes engagement.json: every poll, chat prompt and
// offer cue with its slide number and minute, so the live plan, WebinarJam and the CRM mapper use one timing.
//   node export_from_deck.mjs            writes ./engagement.json
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const cfg = JSON.parse(readFileSync(join(HERE, "../_shared/funnel-config.json"), "utf8"));
const { slides } = (await import(join(HERE, "../16-deck/build/spec.mjs"))).default(cfg);
const L = "ABCDEFG";
const findPoll = (v) => (!v ? null : v.type === "poll" ? v : findPoll(v.a) || findPoll(v.b));
// Offer cues: WebinarJam has no offer timer in a live event; the moderator (behind the scenes, never on camera) launches and closes each one.
// Hide minutes: cue 1 opens with the one-slide offer at minute 20 and closes at minute 25 (webinar.retarget_cutoff_minute),
// cue 2 closes two minutes into the full offer, cue 3 stays to the end.
const HIDE = { cta1_soft: cfg.webinar.retarget_cutoff_minute, cta2_checkpoint: 35, cta3_main: cfg.webinar.duration_minutes };
const WINDOW = 3; // minutes after a poll opens in which a chat letter counts as that poll's answer

const polls = [], chats = [], ctas = [];
slides.forEach((s, i) => {
  const slide = i + 1;
  const p = findPoll(s.visual);
  if (p) polls.push({ poll_id: s.pollId, crm_column: `poll_${s.pollId}`, slide, slide_id: s.id, opens_at_minute: s.min[0], window_minutes: WINDOW,
    question: p.q, options: p.options.map((o, k) => ({ letter: L[k], text: typeof o === "string" ? o : o.text })) });
  if (s.chat) chats.push({ slide, slide_id: s.id, minute: s.min[0], prompt: s.chat });
  if (s.cta) ctas.push({ cta_id: s.cta, slide, slide_id: s.id, show_at_minute: s.min[0], hide_at_minute: HIDE[s.cta],
    button_text: "Book My Call", link: `${cfg.booking.round_robin_url.split(" ")[0]}?utm_source=webinarjam&utm_medium=live_offer&utm_content=${s.cta}` });
});
polls.forEach((p, k) => { const next = polls[k + 1]; if (next) p.window_minutes = Math.min(WINDOW, next.opens_at_minute - p.opens_at_minute); });
const out = { _about: "Generated by export_from_deck.mjs from deliverables/16-deck/build/spec.mjs. Do not edit by hand: change the deck spec and rerun.",
  booked_keyword: "BOOKED", polls, chats, ctas };
writeFileSync(join(HERE, "engagement.json"), JSON.stringify(out, null, 1) + "\n");
console.log(`engagement.json: ${polls.length} polls, ${chats.length} chat prompts, ${ctas.length} offer cues`);

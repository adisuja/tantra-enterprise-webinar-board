// Build step for the Worker: bundles the files in ../public into a generated module.
// (Files are bundled into the script instead of Workers assets, so a deploy needs only one API token.)
const fs = require('fs');
const path = require('path');
const pub = path.join(__dirname, '..', 'public');
const files = {};
const TEXT = /\.(html|js|css|json|webmanifest|svg|txt)$/;
for (const name of fs.readdirSync(pub)) {
  const buf = fs.readFileSync(path.join(pub, name));
  files['/' + name] = TEXT.test(name) ? buf.toString('utf8') : { b64: buf.toString('base64') };
}
fs.writeFileSync(path.join(__dirname, 'assets.generated.js'), '// Generated by build.js. Do not edit.\nexport default ' + JSON.stringify(files) + ';\n');
console.log('bundled', Object.keys(files).length, 'files');

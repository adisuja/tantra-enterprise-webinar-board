#!/usr/bin/env python3
"""Item 12 cold calendar invites: one source for both variants.

python3 build.py                              writes invites.md and calendar-import.csv (merge fields kept)
python3 build.py --tantra [--date YYYY-MM-DD] [--merge]
    writes calendar-tantra.csv for one weekly session with funnel-config values filled.
    --date defaults to webinar.first_date. Without --merge, variant B's greeting line is dropped,
    because Tantra's calendar campaigns are documented as taking no merge tags.
    Refuses while any FILL_ value it needs is still unset.
"""
import csv, datetime, json, pathlib, re, sys

HERE = pathlib.Path(__file__).resolve().parent
CONFIG = HERE.parent / "_shared" / "funnel-config.json"

TAIL = """If it's not relevant, just decline. No follow-up from me.

Get your join link here: {{registration_link}}

The session: {{webinar.title}}
Your host: {{brand.host_name}} ({{brand.host_full_name}}), {{brand.host_title}}. 250+ brands, 21+ countries, 10+ years.

Yes or Maybe keeps the time on your calendar. Your personal join link arrives when you register at the link above."""

VARIANTS = [
    {
        "id": "A", "name": "Meeting-style topic title, no merge fields", "utm": "cal_a",
        "title": "AI revenue generation teardown ({{webinar.duration_minutes}} min)",
        "description": """{{event_date_words}}, {{webinar.start_time_local}}. {{webinar.duration_minutes}} minutes, live online.

For founders who want revenue that doesn't depend on referrals or on them selling every deal. You'll leave with the AI revenue system my team builds, stage by stage: who gets invited, who shows up, who books a sales call.

""" + TAIL,
    },
    {
        "id": "B", "name": "Problem title, first-name greeting", "utm": "cal_b",
        "title": "Founder Pipeline Teardown: Where AI Fits",
        "description": """Hi {{first_name}},

{{event_date_words}}, {{webinar.start_time_local}}. {{webinar.duration_minutes}} minutes, live online.

If your pipeline still runs on referrals and your own calendar, this hour is for you. I'll take a founder's funnel apart stage by stage and show where AI takes over the repetitive work.

""" + TAIL,
    },
]

HEADER = ["variant", "campaign_name", "list_split", "event_title", "description", "date", "time", "minutes", "timezone", "location", "utm_content"]


def source_rows():
    for i, v in enumerate(VARIANTS):
        yield [v["id"], "Enterprise webinar {{event_date}}: calendar (" + v["id"] + ")", f"half {i} of every sender's slice",
               v["title"], v["description"], "{{event_date}}", "{{webinar.start_time_local}}", "{{webinar.duration_minutes}}",
               "{{webinar.timezone}}", "{{registration_link}}", v["utm"]]


def shown(text):
    """Title as a guest sees it, with config values filled (for the character count)."""
    cfg = json.loads(CONFIG.read_text())
    return text.replace("{{webinar.duration_minutes}}", str(cfg["webinar"]["duration_minutes"]))


def write_source():
    with open(HERE / "calendar-import.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(HEADER)
        w.writerows(source_rows())
    md = ["# Cold Calendar Invites (generated by build.py: edit the copy there, then rerun)", ""]
    for v in VARIANTS:
        md += [f"## Variant {v['id']}: {v['name']}", "", "**Event title (as it shows in Google Calendar):**", "", "```text", v["title"], "```", "",
               f"{len(shown(v['title']))} characters as rendered. Calendar grid preview (first 24): `{shown(v['title'])[:24]}`", "",
               "**Event description:**", "", "```text", v["description"], "```", "", f"Link tag: `utm_content={v['utm']}`", ""]
    (HERE / "invites.md").write_text("\n".join(md))
    print("wrote calendar-import.csv and invites.md")


def write_tantra(date_arg, merge):
    cfg = json.loads(CONFIG.read_text())
    def get(path):
        v = cfg
        for k in path.split("."):
            v = v[k]
        return v
    date_s = date_arg or get("webinar.first_date")
    try:
        d = datetime.date.fromisoformat(date_s)
    except ValueError:
        sys.exit(f"not written, set a real date (got {date_s!r}): use --date YYYY-MM-DD or fill webinar.first_date")
    words = f"{d.strftime('%A')} {d.day} {d.strftime('%B')}"
    t = re.search(r"\b(\d{1,2}):(\d{2})\b", str(get("webinar.start_time_local")))
    domain = get("domains.funnel_domain")
    base = (domain if domain.startswith("http") else "https://" + domain).rstrip("/") + get("domains.paths.registration")
    out = []
    for v in VARIANTS:
        link = f"{base}?utm_source=calendar&utm_medium=invite&utm_campaign=enterprise-webinar&utm_content={v['utm']}"
        desc = v["description"]
        desc = desc.replace("Hi {{first_name}},\n\n", "Hi {{firstName}},\n\n" if merge else "")
        desc = desc.replace("{{event_date_words}}", words).replace("{{registration_link}}", link)
        desc = re.sub(r"\{\{((?:webinar|brand)\.[a-z_]+)\}\}", lambda m: str(get(m.group(1))), desc).replace("\n", "<br>")
        title = re.sub(r"\{\{((?:webinar|brand)\.[a-z_]+)\}\}", lambda m: str(get(m.group(1))), v["title"])
        out.append([v["id"], f"Enterprise webinar {d.isoformat()}: calendar ({v['id']})", f"half {VARIANTS.index(v)} of every sender's slice",
                    title, desc, d.isoformat(), f"{int(t.group(1)):02d}:{t.group(2)}" if t else "FILL_TIME_HH_MM",
                    get("webinar.duration_minutes"), get("webinar.timezone"), link, v["utm"]])
    missing = sorted({m for r in out for c in r for m in re.findall(r"FILL_[A-Z_]+", str(c))})
    if missing:
        sys.exit("not written, fill these in funnel-config.json first: " + ", ".join(missing))
    with open(HERE / "calendar-tantra.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(HEADER)
        w.writerows(out)
    print("wrote calendar-tantra.csv")


if __name__ == "__main__":
    if "--tantra" in sys.argv:
        a = sys.argv
        if "--date" in a and (a.index("--date") + 1 >= len(a) or a[a.index("--date") + 1].startswith("--")):
            sys.exit("--date needs a value: --date YYYY-MM-DD")
        write_tantra(a[a.index("--date") + 1] if "--date" in a else None, "--merge" in a)
    else:
        write_source()
